export function t(key: string, lang: Language): string {
  return translations[lang][key as keyof typeof translations['en']] || key;
}

/**
 * The language to use when none is stored yet: the first browser language we support, else English.
 * `languages` is the browser's preference list (`navigator.languages`), e.g. ["de-AT", "en"].
 */
export function detectLanguage(languages: readonly string[] | undefined): Language {
  for (const tag of languages ?? []) {
    const base = tag.toLowerCase().split("-")[0];
    if (base === "de" || base === "en") return base;
  }
  return "en";
}
